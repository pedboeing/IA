# Aplicando as transformações e removendo linhas que ainda restarem com NaN se necessário
df_encoded = df_cleaned.copy()
for col, mapping in mappings.items():
    if col in df_encoded.columns:
        df_encoded[col] = df_encoded[col].map(mapping)

print("\nDados transformados em números (após correção):")
display(df_encoded.head(15))

import seaborn as sns
import matplotlib.pyplot as plt

# 1. Resumo estatístico
print("Resumo Estatístico dos Dados:")
display(df_encoded.describe())

# 2. Matriz de correlação
plt.figure(figsize=(12, 8))
correlation_matrix = df_encoded.drop(columns=['timestamp']).corr()

