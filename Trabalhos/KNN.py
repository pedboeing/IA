from sklearn.model_selection import train_test_split

# Definindo as variáveis preditoras (X) e a variável alvo (y)
# Removendo a coluna 'timestamp' e o alvo 'gripe_ano_passado'
X = df_cleaned.drop(columns=['timestamp', 'gripe_ano_passado'])
y = df_cleaned['gripe_ano_passado']

# Realizando a divisão: 75% treino e 25% teste
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42)

print(f"Tamanho do conjunto de treino: {len(X_train)}")
print(f"Tamanho do conjunto de teste: {len(X_test)}")

# Verificando valores únicos para garantir que o mapeamento funcione
cols_to_check = ['viajou', 'horas_sono', 'lavagem_maos', 'estresse']
print("Valores únicos encontrados nas colunas:")
