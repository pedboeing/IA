from sklearn.model_selection import train_test_split

# Separando as variáveis preditoras (X) do alvo (y) usando o dataframe codificado
# Removemos 'timestamp' por ser apenas um identificador
X = df_encoded.drop(columns=['timestamp', 'gripe_ano_passado'])
y = df_encoded['gripe_ano_passado']

# Dividindo em 75% treino e 25% teste
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, random_state=42)

print(f"Conjunto de Treino: {len(X_train)} amostras")
print(f"Conjunto de Teste: {len(X_test)} amostras")

print("\nExemplo das variáveis de treino (X_train):")
display(X_train.head())

from sklearn.neighbors import KNeighborsClassifier
from sklearn.model_selection import GridSearchCV

# Definindo o modelo base
knn = KNeighborsClassifier()

# Definindo o espaço de busca de hiperparâmetros
param_grid = {
    'n_neighbors': [3, 5, 7, 9, 11, 13, 15, 17, 19],
    'weights': ['uniform', 'distance'],
    'metric': ['euclidean', 'manhattan', 'minkowski']
}

# Configurando o GridSearchCV com 5-fold cross-validation
grid_search = GridSearchCV(knn, param_grid, cv=5, scoring='accuracy', n_jobs=-1)

# Treinando o grid search
grid_search.fit(X_train, y_train)

# Resultados
print(f"Melhores parâmetros encontrados: {grid_search.best_params_}")
print(f"Melhor acurácia no cross-validation: {grid_search.best_score_:.4f}")

# Avaliando no conjunto de teste
best_model = grid_search.best_estimator_
test_accuracy = best_model.score(X_test, y_test)
print(f"Acurácia final no conjunto de teste: {test_accuracy:.4f}")